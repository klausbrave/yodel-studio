import { maxNotes, validPhrase, type Note, type Phrase } from "./score";

export interface Song {
  title: string;
  baseBpm: number;
  phrase: Phrase;
}

export const maxTitle = 80;
export const songFragment = "#song=";
const maxBytes = 160 * 1024;
const maxEncoded = Math.ceil(maxBytes * 4 / 3);

export function validTitle(title: unknown): title is string {
  return typeof title === "string" && title.length > 0 && title.length <= maxTitle &&
    title === title.trim() && !/[\u0000-\u001f\u007f]/.test(title);
}

export function validSong(value: unknown): value is Song {
  const song = value as Song | null;
  return !!song && validTitle(song.title) &&
    Number.isInteger(song.baseBpm) && song.baseBpm >= 60 && song.baseBpm <= 200 && validPhrase(song.phrase);
}

// A permalink carries the music. Internal editor IDs are regenerated by the recipient.
function scoreFields({ midi, beats, syllable, register, rest, larynx, root, tongue, mouth }: Note) {
  return { midi, beats, syllable, register, rest, larynx, root, tongue, mouth };
}

function encodedBytes(bytes: Uint8Array) {
  let binary = "";
  for (let i = 0; i < bytes.length; i += 4096) {
    binary += String.fromCharCode(...bytes.subarray(i, i + 4096));
  }
  return btoa(binary).replaceAll("+", "-").replaceAll("/", "_").replace(/=+$/, "");
}

async function readBounded(stream: ReadableStream<Uint8Array>) {
  const reader = stream.getReader();
  const chunks: Uint8Array[] = [];
  let length = 0;
  try {
    while (true) {
      const { done, value } = await reader.read();
      if (done) break;
      length += value.length;
      if (length > maxBytes) {
        await reader.cancel();
        throw new Error("Song exceeds the sharing limit.");
      }
      chunks.push(value);
    }
  } finally {
    reader.releaseLock();
  }
  const bytes = new Uint8Array(length);
  let offset = 0;
  for (const chunk of chunks) {
    bytes.set(chunk, offset);
    offset += chunk.length;
  }
  return bytes;
}

export async function songUrl({ title, baseBpm, phrase }: Song, address: string) {
  const { bpm, transpose, leadBeats, notes } = phrase;
  const data = new TextEncoder().encode(JSON.stringify({
    title, baseBpm, phrase: { bpm, transpose, leadBeats, notes: notes.map(scoreFields) },
  }));
  if (data.length > maxBytes) throw new Error("Song exceeds the sharing limit.");
  // Deflate is a standard wire format. The plain variant also works without CompressionStream.
  const compressed = typeof CompressionStream === "function";
  const bytes = compressed
    ? await readBounded(new Blob([data]).stream().pipeThrough(new CompressionStream("deflate")))
    : data;
  const url = new URL(address);
  url.search = "";
  url.hash = songFragment + (compressed ? "1z." : "1j.") + encodedBytes(bytes);
  return url.href;
}

export async function readSong(hash: string): Promise<Song> {
  if (!hash.startsWith(songFragment) || hash.length > songFragment.length + 3 + maxEncoded)
    throw new Error("Invalid song link.");
  const mode = hash.slice(songFragment.length, songFragment.length + 3);
  const payload = hash.slice(songFragment.length + 3);
  if ((mode !== "1z." && mode !== "1j.") || !/^[A-Za-z0-9_-]+$/.test(payload))
    throw new Error("Unrecognized song link.");
  const data = Uint8Array.from(atob(payload.replaceAll("-", "+").replaceAll("_", "/")), (c) => c.charCodeAt(0));
  if (data.length > maxBytes) throw new Error("Song exceeds the sharing limit.");
  if (mode === "1z." && typeof DecompressionStream !== "function")
    throw new Error("This song link needs a browser with decompression support.");
  const bytes = mode === "1z."
    ? await readBounded(new Blob([data]).stream().pipeThrough(new DecompressionStream("deflate")))
    : data;
  const raw = JSON.parse(new TextDecoder("utf-8", { fatal: true }).decode(bytes));
  const source = raw?.phrase;
  if (!Array.isArray(source?.notes) || !source.notes.length || source.notes.length > maxNotes)
    throw new Error("Invalid song score.");
  const song = {
    title: raw.title,
    baseBpm: raw.baseBpm,
    phrase: {
      bpm: source.bpm, transpose: source.transpose, leadBeats: source.leadBeats,
      notes: source.notes.map((note: Note, i: number) => ({ ...scoreFields(note), id: "n" + i })),
    },
  };
  if (!validSong(song)) throw new Error("Invalid song score.");
  return song;
}
